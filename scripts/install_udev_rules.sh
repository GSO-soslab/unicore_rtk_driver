#!/usr/bin/env bash
# Give a plugged-in GNSS receiver a stable name, e.g. /dev/mjrtk_um982.
#
#   scripts/install_udev_rules.sh /dev/ttyUSB0 mjrtk_um982
#   scripts/install_udev_rules.sh --dry-run /dev/ttyUSB0 mjrtk_um982
#
# Writes /etc/udev/rules.d/99-<name>.rules (matching the adapter's serial
# number, or vendor/product + USB port if it has none), reloads udev and adds
# the current user to the dialout group.  Needs sudo except with --dry-run.
set -euo pipefail

dry_run=0
if [[ "${1:-}" == "--dry-run" ]]; then
    dry_run=1
    shift
fi

if [[ $# -ne 2 ]]; then
    sed -n '2,10p' "$0" | sed 's/^# \{0,1\}//'
    exit 1
fi

device="$1"
name="$2"
rules_file="/etc/udev/rules.d/99-${name}.rules"

if [[ ! -e "$device" ]]; then
    echo "error: $device does not exist" >&2
    exit 1
fi
if [[ ! "$name" =~ ^[A-Za-z0-9_-]+$ ]]; then
    echo "error: name may only contain letters, digits, '_' and '-'" >&2
    exit 1
fi

# Attributes of the first USB device up the tree from the tty (the adapter
# itself; parents such as the root hub must not be used).
usb_block() {
    udevadm info -a -n "$device" | awk '
        /looking at/ { if (found) exit; block = "" }
        { block = block $0 "\n" }
        /ATTRS\{idVendor\}==/ { found = 1 }
        END { if (found) printf "%s", block }'
}
block="$(usb_block)"
usb_attr() {
    printf '%s\n' "$block" | sed -n "s/^ *$1==\"\(.*\)\"$/\1/p" | head -n 1
}

vendor="$(usb_attr 'ATTRS{idVendor}')"
product="$(usb_attr 'ATTRS{idProduct}')"
serial="$(usb_attr 'ATTRS{serial}')"
port="$(usb_attr 'KERNELS')"

if [[ -z "$vendor" || -z "$product" ]]; then
    echo "error: $device is not a USB serial device" >&2
    exit 1
fi

match="SUBSYSTEM==\"tty\", ATTRS{idVendor}==\"$vendor\", ATTRS{idProduct}==\"$product\""
if [[ -n "$serial" ]]; then
    match+=", ATTRS{serial}==\"$serial\""
    note="matched by serial number $serial"
else
    match="SUBSYSTEM==\"tty\", KERNELS==\"$port\", ATTRS{idVendor}==\"$vendor\", ATTRS{idProduct}==\"$product\""
    note="adapter has no serial number: matched by USB port $port (keep it plugged into that port)"
fi
rule="$match, SYMLINK+=\"$name\", GROUP=\"dialout\", MODE=\"0660\""

echo "# $name: $vendor:$product, $note"
echo "$rule"
if [[ $dry_run -eq 1 ]]; then
    exit 0
fi

printf '# Generated by unicore_rtk_driver/scripts/install_udev_rules.sh\n# %s\n%s\n' \
    "$note" "$rule" | sudo tee "$rules_file" > /dev/null
sudo udevadm control --reload-rules
sudo udevadm trigger --subsystem-match=tty
echo "installed $rules_file -> /dev/$name"

if ! id -nG "$USER" | grep -qw dialout; then
    sudo usermod -aG dialout "$USER"
    echo "added $USER to dialout: log out and back in for it to take effect"
fi
